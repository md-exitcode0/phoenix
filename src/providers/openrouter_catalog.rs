//! WHY THIS IS A GENERATED TABLE AND NOT A HAND-PICKED SHORTLIST
//!
//! OpenRouter is an aggregator: its ids (`vendor/model[:tier]`) are the ONLY
//! names the API answers to, and the same base model carries a DIFFERENT
//! context window per tier. `nvidia/nemotron-3-ultra-550b-a55b` is 512288
//! tokens; the `:free` tier of that same model is 1000000. Resolving a tier
//! suffix by stripping it and matching the base therefore produces the WRONG
//! window — which is why every entry here is listed at its full id.
//!
//! `effort` is not a guess either: it mirrors `reasoning_effort` in the
//! model's `supported_parameters`. A model that does not advertise it must not
//! be handed an effort ladder, or the UI grows a control the API ignores.
//!
//! `tools` mirrors `tools` in `supported_parameters`. A model without it
//! cannot call a tool at all — and since a Phoenix turn only ends when the
//! model calls `final_answer`, assigning a no-tools model to an agent lane
//! produces exactly the "it wrote prose and then just stopped" failure.

