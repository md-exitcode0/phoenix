/// Row lookup by exact id. Exact only, deliberately: a tier suffix changes the
/// context window, so a fuzzy match here would reintroduce the bug this table
/// exists to fix.
pub fn find(model_id: &str) -> Option<&'static OpenRouterModel> {
    OPENROUTER_MODELS.iter().find(|row| row.0 == model_id)
}

/// Does this OpenRouter model accept `reasoning: { effort }`?
pub fn takes_effort(model_id: &str) -> bool {
    find(model_id).map(|row| row.4).unwrap_or(false)
}

/// Can this model call tools? Unknown ids answer `true` — a model we have not
/// catalogued must not be blocked from a lane on our ignorance.
pub fn supports_tools(model_id: &str) -> bool {
    find(model_id).map(|row| row.5).unwrap_or(true)
}

/// Free-tier models only — the picker's default filter, since this project
/// runs on free lanes.
pub fn free_models() -> impl Iterator<Item = &'static OpenRouterModel> {
    OPENROUTER_MODELS.iter().filter(|row| row.6)
}
