/// Does this (provider, model) accept a named reasoning effort?
pub fn takes_effort(provider_id: &str, model_id: &str) -> Option<bool> {
    row(provider_id, model_id).map(|r| r.4)
}

/// Can this (provider, model) call tools? A turn only ends when the model calls
/// `final_answer`, so a lane assigned a no-tools model can never finish one.
pub fn supports_tools(provider_id: &str, model_id: &str) -> Option<bool> {
    row(provider_id, model_id).map(|r| r.5)
}

/// Is this row's metadata sourced, or is it a fallback carrying a default?
pub fn is_verified(provider_id: &str, model_id: &str) -> Option<bool> {
    row(provider_id, model_id).map(|r| r.6)
}

fn row(provider_id: &str, model_id: &str) -> Option<&'static CatalogRow> {
    table_for(provider_id)?.iter().find(|r| r.0 == model_id)
}
