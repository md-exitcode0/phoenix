//! Provider model catalogs, generated rather than hand-maintained.
//!
//! Every hand-written window in this project drifted, and each drift produced
//! the same bug: the context gauge reads high and auto-compaction fires early,
//! because the runtime divides by a number nobody re-checked after the vendor
//! changed it. Sonnet 4.6 sat at 200k while serving 1M; the GPT-5.4+ line sat
//! at 272k while serving 1.05M.
//!
//! SOURCES, in descending order of authority (all fetched 2026-07-29):
//!
//!   1. THE PROVIDER\'S OWN METADATA — venice, chutes, deepinfra, huggingface
//!      publish context length (and Venice publishes `supportsReasoningEffort`
//!      outright) on their public `/models`. Nothing beats the server telling
//!      you what it serves.
//!   2. THE PROVIDER\'S ID LIST + a resolved match — nvidia and ollama-cloud
//!      return ids and nothing else, so capabilities come from matching the
//!      same underlying model in the aggregator catalog.
//!   3. THE AGGREGATOR\'S SERVED NUMBERS — openai, anthropic, google, xai, meta.
//!      No API key is held for these, so the figure is what the aggregator
//!      measures serving the identical model. A measurement, not a press release.
//!   4. CURATED IDS, REFRESHED — key-gated providers (groq, mistral, together,
//!      fireworks, moonshot, zai, cerebras, ...) 401/403 without a key, so their
//!      model LIST stays curated while windows and capabilities are refreshed
//!      from a resolved match.
//!
//! `verified` is false where no source covered the model and the row carries
//! its curated or family-default value. Those rows stay listed — a real id the
//! picker can offer beats hiding it — but nothing may present them as fact.

/// `(id, display name, context window, reasoning, takes reasoning_effort, tool calling, verified)`
pub type CatalogRow = (&'static str, &'static str, u32, bool, bool, bool, bool);

