import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const context={};vm.runInNewContext(await readFile(new URL('../monocode/ui/fluffy-activity.js',import.meta.url),'utf8'),context);
const create=context.PhoenixFluffyActivity.createStore;
const execution=n=>({turn_id:`turn-${n}`,task_id:`turn-${n}`,attempt_id:`attempt-${n}`});
const owned={agentId:'school_coach',sessionId:'agent-school_coach'};
const store=create();
store.begin({...owned,execution:execution(1),sequence:1});
store.registry({...owned,status:'working',label:'Thinking'});
store.ingest({...owned,execution:execution(1),sequence:2,kind:'tool_start',event:{tool:'read',call_id:'read-1'}});
store.ingest({...owned,execution:execution(1),sequence:3,kind:'settled',event:{ok:true}});
assert.equal(store.snapshot(owned.agentId).terminal,true);
store.registry({...owned,status:'working',label:'Thinking'});
assert.equal(store.snapshot(owned.agentId).mode,'success','a stale directory poll cannot revive completed work');
store.settleFinite(owned.agentId,store.snapshot(owned.agentId).revision);
store.registry({...owned,status:'using_tool',label:'Reading a file'});
assert.equal(store.snapshot(owned.agentId).mode,'idle','completed animation stays idle through delayed running polls');
store.registry({...owned,status:'idle'});
store.registry({...owned,status:'working',label:'Thinking'});
assert.equal(store.snapshot(owned.agentId).terminal,false,'a real idle-to-working boundary starts new legacy work');
assert.equal(store.snapshot(owned.agentId).mode,'thinking');
assert.equal(store.ingest({...owned,execution:execution(1),sequence:4,kind:'tool_start',event:{tool:'read',call_id:'late-old'}}),false,'late completed execution stays retired');
store.begin({...owned,execution:execution(2),sequence:5});
store.ingest({...owned,execution:execution(2),sequence:6,kind:'ask_pending'});
store.ingest({...owned,execution:execution(2),sequence:7,kind:'settled',event:{ok:true}});
assert.equal(store.snapshot(owned.agentId).mode,'waiting','a final reply does not answer a pending question');
store.registry({...owned,status:'waiting_user'});
assert.equal(store.snapshot(owned.agentId).mode,'waiting');
store.begin({...owned,execution:execution(3),sequence:8});
store.ingest({...owned,execution:execution(3),sequence:9,kind:'settled',event:{ok:true}});
store.registry({...owned,status:'working',kind:'user',event:{turn_id:'turn-4'}});
assert.equal(store.snapshot(owned.agentId).terminal,false,'an authored new turn can start without an intermediate idle poll');
const legacy=create();
legacy.registry({...owned,status:'working',kind:'user',event:{turn_id:'legacy-1'}});
legacy.registry({...owned,status:'working',kind:'settled',event:{turn_id:'legacy-1',ok:true}});
legacy.registry({...owned,status:'working',label:'Thinking'});
assert.equal(legacy.snapshot(owned.agentId).terminal,true,'legacy completion also fences stale registry polls');
assert.equal(legacy.snapshot(owned.agentId).mode,'success');
const switched={...owned,sessionId:'agent-school-coach-new'};
legacy.begin({...owned,execution:execution(5),sequence:10});
legacy.ingest({...owned,execution:execution(5),sequence:11,kind:'settled',event:{ok:true}});
legacy.registry({...switched,status:'working',label:'Thinking'});
assert.equal(legacy.snapshot(owned.agentId).mode,'thinking','new session registry is independent of the previous terminal execution');
assert.equal(legacy.snapshot(owned.agentId).terminal,false);
assert.equal(legacy.registry({...owned,status:'working'}),false,'retired session cannot restore previous work');
const nativeFinished=create();
nativeFinished.begin({...owned,execution:execution(6),sequence:12});
nativeFinished.registry({...owned,status:'working',kind:'settled',event:{ok:true}});
assert.equal(nativeFinished.ingest({...owned,execution:execution(6),sequence:13,kind:'tool_start',event:{tool:'read',call_id:'late-native'}}),false,'native terminal receipt fences late structured tools too');
assert.equal(nativeFinished.snapshot(owned.agentId).mode,'success');
console.log('PASS fluffy completion, delayed polls, new turns, session ownership, and pending questions');
