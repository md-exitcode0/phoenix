// Builds canvas-app/ui/avatar-morphs.js from the two avatar morph sources:
//  - avatars/source/phoenix-morph.svg — the original logo morph (INBETWEEN SMIL
//    export: 60 <use> poses, each visible for its own keyTimes window);
//  - avatars/source/orbit-morph.svg — the second mark, the same kind of export.
// Output keeps only path geometry (rounded to 0.1) and a pose timeline; the UI
// supplies the gradient and decides when to play. Run: node scripts/build-avatar-morphs.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ui = path.join(root, "canvas-app/ui");
const source = (name) => path.join(ui, "avatars/source", name);

const round = (d) => d.replace(/-?\d*\.?\d+(?:e-?\d+)?/gi, (n) => String(Math.round(Number(n) * 10) / 10));
const pathsOf = (markup) => [...markup.matchAll(/<path\b[^>]*\sd="([^"]+)"/g)].map((m) => round(m[1]));

function bbox(poses) {
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const pose of poses) for (const d of pose) {
    // Every source path is absolute M/C/Z, so the numbers alternate x, y.
    const numbers = d.match(/-?\d*\.?\d+/g).map(Number);
    for (let i = 0; i + 1 < numbers.length; i += 2) {
      minX = Math.min(minX, numbers[i]); maxX = Math.max(maxX, numbers[i]);
      minY = Math.min(minY, numbers[i + 1]); maxY = Math.max(maxY, numbers[i + 1]);
    }
  }
  // Square and padded, so both marks sit the same size in a round avatar.
  const size = Math.max(maxX - minX, maxY - minY) * 1.12;
  const cx = (minX + maxX) / 2, cy = (minY + maxY) / 2;
  return [cx - size / 2, cy - size / 2, size, size].map((n) => Math.round(n * 10) / 10);
}

function assertAbsolute(poses, name) {
  for (const pose of poses) for (const d of pose) {
    if (/[^MCZ\d\s.,-]/.test(d)) throw new Error(`${name}: only absolute M/C/Z paths are supported`);
  }
}

// An INBETWEEN SMIL export: pose groups in <defs>, then one <use> per
// timeline slot, each visible for its own keyTimes window. `rotate` turns the
// whole mark clockwise (degrees) about its resting pose's centre.
function smil(file, name, rotate = 0) {
  const svg = fs.readFileSync(source(file), "utf8");
  if (/transform=/.test(svg)) throw new Error(`${file}: transforms are not supported`);
  const poseIds = [];
  let poses = [];
  const starts = [...svg.matchAll(/<g id="(morph-pose-\d+)">/g)];
  starts.forEach((match, i) => {
    const end = i + 1 < starts.length ? starts[i + 1].index : svg.indexOf("</defs><use");
    poseIds.push(match[1]);
    poses.push(pathsOf(svg.slice(match.index, end)));
  });
  const duration = Number(/dur="(\d+)ms"/.exec(svg)[1]);
  const timeline = [];
  for (const use of svg.matchAll(/<use href="#(morph-pose-\d+)"[^>]*><animate[^>]*values="([^"]+)"[^>]*keyTimes="([^"]+)"/g)) {
    const values = use[2].split(";"), times = use[3].split(";").map(Number);
    const at = values.indexOf("visible");
    timeline.push([poseIds.indexOf(use[1]), times[at], times[at + 1] ?? 1]);
  }
  timeline.sort((a, b) => a[1] - b[1]);
  assertAbsolute(poses, file);
  if (rotate) {
    const [x, y, w, h] = bbox([poses[timeline[0][0]]]), cx = x + w / 2, cy = y + h / 2;
    const cos = Math.cos(rotate * Math.PI / 180), sin = Math.sin(rotate * Math.PI / 180);
    // Rotating every point (Bezier control points included) is exact.
    poses = poses.map((pose) => pose.map((d) => {
      let pending = null;
      return round(d.replace(/-?\d*\.?\d+/g, (n) => {
        if (pending === null) { pending = Number(n); return "\u0000"; }
        const px = pending - cx, py = Number(n) - cy; pending = null;
        return `${cx + px * cos - py * sin} ${cy + px * sin + py * cos}`;
      }).replace(/\u0000 ?/g, ""));
    }));
  }
  // Framed on the resting pose; in-between poses may spill a little past it.
  return { name, duration, mode: "loop", viewBox: bbox([poses[timeline[0][0]]]), poses, timeline };
}

const morphs = {
  phoenix: smil("phoenix-morph.svg", "Phoenix"),
  // Turned 35° clockwise so the eyes sit closer to level (the user's pick).
  orbit: smil("orbit-morph.svg", "Orbit", Number(process.env.ORBIT_ROTATE ?? 35)),
};
for (const [id, morph] of Object.entries(morphs)) {
  morph.timeline = morph.timeline.map(([pose, t0, t1]) => [pose, Math.round(t0 * 1e4) / 1e4, Math.round(t1 * 1e4) / 1e4]);
  console.log(`${id}: ${morph.poses.length} poses, ${morph.timeline.length} slots, ${morph.duration}ms ${morph.mode}, viewBox ${morph.viewBox.join(" ")}`);
}
const out = `// Generated by scripts/build-avatar-morphs.mjs — do not edit by hand.\nwindow.PHOENIX_MORPHS = ${JSON.stringify(morphs)};\n`;
fs.writeFileSync(path.join(ui, "avatar-morphs.js"), out);
console.log(`wrote canvas-app/ui/avatar-morphs.js (${Math.round(out.length / 1024)} KB)`);
