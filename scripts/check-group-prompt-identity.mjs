import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../canvas-app/ui/conversation.js',import.meta.url),'utf8');
const context=vm.createContext({state:{item:{kind:'group'}},displayRole:e=>e.value.role,
 displayTurnId:e=>e.turn_id||'',incomingAgentTalkKey:()=>'',imageCommentUserMirrors:()=>false,
 displaySemantic:e=>e.value.text,ownedStoryEventKey:()=>''});
vm.runInContext(source.slice(source.indexOf('  function equivalentDisplayRows('),source.indexOf('  const PRE_ANSWER_RECOVERY_ROLES')),context);
const user=(turn,text)=>({source:'history',turn_id:turn,value:{role:'user',text}});
assert(context.equivalentDisplayRows(user('turn-one','Theo continue'),user('turn-one','@researcher continue')));
assert(!context.equivalentDisplayRows(user('turn-one','Continue'),user('turn-two','Continue')));
assert(!context.equivalentDisplayRows(user('legacy-1','First'),user('legacy-1','Second')));
context.state.item.kind='agent';
assert(!context.equivalentDisplayRows(user('turn-one','First'),user('turn-one','Second')));
console.log('Group prompt identity survives changed mention display; repeated prompts in distinct turns remain distinct.');
context.state.item.kind='group';
context.historyVisibleInConversation=()=>true;
context.recoveredInsertionIndex=()=>-1;
context.ensureDisplayTurnIds=rows=>rows;
context.trimDisplayRows=rows=>rows;
context.repairHandoffReturnOrder=rows=>({rows,changed:false});
context.replaceDisplayRows=(rows,dirty)=>{context.state.displayRows=rows;context.state.displayDirty=Boolean(dirty);};
vm.runInContext(source.slice(source.indexOf('  function reconcileHistory('),source.indexOf('  function normalizeAskRecord(')),context);
context.state.displayRows=[user('turn-first','First'),user('turn-latest','Latest')];
const canonical=[{role:'user',turn_id:'turn-first',text:'First'},{role:'user',text:'Recovered older prompt'},{role:'user',turn_id:'turn-latest',text:'Latest'}];
const result=context.reconcileHistory(canonical);
assert.equal(result.added.length,1);assert.equal(result.reordered,true);
assert.deepEqual(Array.from(context.state.displayRows,e=>e.value.text),['First','Recovered older prompt','Latest']);
assert.equal(context.reconcileHistory(canonical).added.length,0);
console.log('Recovered older prompt stays before the latest exchange and a second catch-up adds nothing.');

const first=user('first','Continue'),older=user('older','Continue'),latest=user('latest','Latest'),pending=user('pending','Local queued prompt');
const reply=(turn,text)=>({source:'history',turn_id:turn,value:{role:'group_message',text}});
const firstReply=reply('first','First reply'),olderReply=reply('older','Older reply'),latestReply=reply('latest','Latest reply');
context.state.displayDirty=false;
context.state.displayRows=[first,firstReply,latest,latestReply,older,olderReply,pending];
const authored=[first,older,latest].map(e=>({...e.value,turn_id:e.turn_id}));
const repaired=context.reconcileHistory(authored);
assert.equal(repaired.added.length,0);
assert.equal(repaired.reordered,true);
assert.equal(context.state.displayDirty,true);
assert.deepEqual(Array.from(context.state.displayRows),[first,firstReply,older,olderReply,latest,latestReply,pending]);
assert.equal(context.reconcileHistory(authored).reordered,false);
context.state.item.kind='agent';
context.state.displayRows=[latest,latestReply,first,firstReply];
context.reconcileHistory(authored.filter(e=>e.turn_id!=='older'));
assert.deepEqual(Array.from(context.state.displayRows),[latest,latestReply,first,firstReply]);
console.log('Persisted group order is repaired with replies attached, repeated prompts retained, local queue preserved, and direct chats unchanged.');

context.state.item.kind='group';
context.state.displayRows=[latest,latestReply,first,firstReply];
let repaints=0,persists=0;
context.ui={invoke:async()=>authored.filter(e=>e.turn_id!=='older')};
context.selectionIsCurrent=()=>true;
context.$=()=>({querySelector:()=>null});
context.conversationScrollBookmark=()=>({});
context.repaintConversation=()=>{repaints++;};
context.syncRestoredWorkVisibility=()=>{};
context.scheduleDisplayPersist=()=>{persists++;};
context.flushOwnedStories=()=>{};
vm.runInContext(source.slice(source.indexOf('  async function catchUpConversation('),source.indexOf('  function subscribeJournal(')),context);
await context.catchUpConversation({sessionId:'isolated',owner:{kind:'group'}});
assert.equal(repaints,1);
assert.equal(persists,1);
assert.deepEqual(Array.from(context.state.displayRows),[first,firstReply,latest,latestReply]);
console.log('Catch-up repaints and persists an order-only repair with no newly added messages.');
