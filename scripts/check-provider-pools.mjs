import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../canvas-app/ui/settings.js',import.meta.url),'utf8');
const profiles=[{id:'openai-codex:3',display:'VSPARK PRO 5X',method:'oauth'},{id:'openai-codex:2',display:'Work <account>',method:'oauth'}];
let saved,html='',renders=0;
const button={};
const c=vm.createContext({state:{providerCatalog:{providers:[{id:'openai-codex',profiles}]},modelSaving:false},ui:{showModal:value=>{html=value;},closeModal:()=>{},toast:()=>{},providerIcon:()=>'<i></i>'},escape:v=>String(v).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;'),$:()=>({querySelector:()=>button}),nativeOr:async(name,args)=>{saved={name,args};},renderModels:async()=>{renders++;}});
vm.runInContext(source.slice(source.indexOf('  function providerAccountLabel('),source.indexOf('  const modelLabels=')),c);
assert.equal(c.providerAccountLabel('openai-codex:3'),'VSPARK PRO 5X');
c.confirmProviderRemoval('openai-codex:3');assert(html.includes('Remove VSPARK PRO 5X?'));assert(!html.includes('Remove openai-codex:3?'));
await c.moveProviderAccount('openai-codex','openai-codex:2',-1);
assert.equal(saved.name,'auth_provider_order');assert.deepEqual(Array.from(saved.args.profileIds),['openai-codex:2','openai-codex:3']);assert.equal(renders,1);assert.equal(c.state.modelSaving,false);
vm.runInContext(source.slice(source.indexOf('  function providerCard('),source.indexOf('  function providerView(')),c);
const card=c.providerCard({id:'openai-codex',name:'OpenAI Codex',profiles,models:[]});
assert(card.includes('Work &lt;account&gt;'));assert(card.includes('data-pool-move="-1"'));
assert(card.includes('data-provider-manage="openai-codex:2"'));
assert(card.includes('aria-label="Manage Work &lt;account&gt;"'));
assert(card.includes('Switching accounts keeps the selected model'));
console.log('Provider names, escaped account labels, priority submission, and compact management controls passed.');
