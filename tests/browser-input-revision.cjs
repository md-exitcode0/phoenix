"use strict";
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../canvas-app/chromium-shell/main.cjs'),'utf8');
const host=()=>({isDestroyed:()=>false,isVisible:()=>true,contentView:{addChildView(){},removeChildView(){}}});
const mainWindow=host(),parked=host();
const context=vm.createContext({mainWindow,renderHost:()=>parked});
vm.runInContext(source.slice(source.indexOf('function detachSurfaceTab('),source.indexOf('async function captureSurfaceTab(')),context);
let bounds={x:0,y:0,width:800,height:600};
const tab={host:mainWindow,leased:false,inputRevision:0,view:{getBounds:()=>({...bounds}),setBounds:rect=>{bounds={...rect};},webContents:{isDestroyed:()=>false}}};
context.attachSurfaceTab(tab,mainWindow,bounds);
assert.equal(tab.inputRevision,0,'identical UI status ticks retain a prepared target');
context.attachSurfaceTab(tab,mainWindow,{...bounds,width:900});
assert.equal(tab.inputRevision,1,'actual viewport changes still invalidate input');
context.parkSurfaceTab(tab,{width:900,height:600});
const before=tab.inputRevision;
const release=context.drawableLease({rect:{width:900,height:600}},tab).lease();
assert.equal(tab.host,mainWindow);
release();
assert.equal(tab.host,parked);
assert.equal(tab.inputRevision,before,'temporary capture and restoration preserve input revision');
const releaseDuringMount=context.drawableLease({rect:{width:900,height:600}},tab).lease();
context.attachSurfaceTab(tab,mainWindow,{x:20,y:20,width:900,height:600});
const changed=tab.inputRevision;
releaseDuringMount();
assert.ok(changed>before,'an external mount during preparation invalidates the target');
assert.equal(tab.host,mainWindow,'lease cleanup cannot undo an external mount');
console.log('Browser input revision checks passed');
